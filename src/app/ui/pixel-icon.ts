@Component({
  selector: 'px-icon',
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `<svg
    class="pix"
    viewBox="0 0 10 10"
    [attr.width]="size()"
    [attr.height]="size()"
    shape-rendering="crispEdges"
    aria-hidden="true"
  >
    <path [attr.d]="path()" fill="currentColor" />
  </svg>`,
  styles: `
    :host {
      display: inline-flex;
      line-height: 0;
    }
  `,
})
export class PixelIcon {
  readonly name = input.required<string>();
  readonly size = input(20);

  protected readonly path = computed(() => {
    const grid = ICONS[this.name()] ?? [];
    let d = '';
    grid.forEach((row, y) => {
      [...row].forEach((c, x) => {
        if (c === '#') d += `M${x} ${y}h1v1h-1z`;
      });
    });
    return d;
  });
}
